import os
import shutil
import subprocess
import tempfile
import unittest

from prod import modulefile, recipe
from prod.errors import FormatError

PRODUCTS = "/home/cupsoft/Products"

PYTHON_TCL = """#%Module
@HEADER@
module-whatis "Python @VERSION@"
conflict PYTHON
@DEPENDS@
setenv       PYTHON_HOME @PREFIX@
prepend-path PATH        @PREFIX@/bin
"""

ROOT_TCL = """#%Module
@HEADER@
module-whatis "ROOT @VERSION@"
conflict ROOT
@DEPENDS@
setenv       ROOTSYS            @PREFIX@
prepend-path PATH               @PREFIX@/bin
prepend-path LD_LIBRARY_PATH    @PREFIX@/lib
prepend-path PYTHONPATH         @PREFIX@/lib
@GENERATED@
"""

ROOT_RECIPE = b"""format: "1"
product: "ROOT"
version: "V6.32.20_3.11.14"
depends:
  - {name: "PYTHON", version: "V3.11.14"}
source: {url: "https://root.cern/download/root_v6.32.20.source.tar.gz"}
"""

TCLSH = shutil.which("tclsh")


def tcl_complete(text):
    """Whether text is a syntactically complete Tcl script (balanced braces, quotes, brackets)."""
    with tempfile.NamedTemporaryFile("w", suffix=".tcl", delete=False) as f:
        f.write(text)
    try:
        r = subprocess.run([TCLSH], input=f"set fh [open {{{f.name}}}]; puts [info complete [read $fh]]",
                           capture_output=True, text=True)
        return r.stdout.strip() == "1"
    finally:
        os.unlink(f.name)


class Sources(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="prod-test-")
        self.src = os.path.join(self.tmp, "modulefiles")
        self.recipes = os.path.join(self.tmp, "recipes")
        self.put_template("PYTHON", PYTHON_TCL)
        self.put_template("ROOT", ROOT_TCL, generate="#!/bin/sh\necho \"setenv ROOT_PREFIX_SEEN $1\"\n")
        self.put_recipe("ROOT", "V6.32.20_3.11.14", ROOT_RECIPE)
        self.put_recipe("PYTHON", "V3.11.14", b'format: "1"\nproduct: "PYTHON"\nversion: "V3.11.14"\n')

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def put_template(self, name, text, generate=None):
        d = os.path.join(self.src, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "template.tcl"), "w") as f:
            f.write(text)
        g = os.path.join(d, "generate")
        if generate is not None:
            with open(g, "w") as f:
                f.write(generate)
            os.chmod(g, 0o755)
        elif os.path.exists(g):
            os.unlink(g)

    def put_recipe(self, name, version, data):
        d = os.path.join(self.recipes, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, version + ".yml"), "wb") as f:
            f.write(data)


class TestSource(Sources):
    def test_load(self):
        s = modulefile.load_source(self.src, "ROOT")
        self.assertEqual(s.home_var, "ROOTSYS")
        self.assertTrue(s.generate.endswith("ROOT/generate"))
        self.assertIsNone(modulefile.load_source(self.src, "PYTHON").generate)

    def test_rules(self):
        cases = {
            "no magic": PYTHON_TCL.replace("#%Module\n", ""),
            "unknown placeholder": PYTHON_TCL + "setenv X @SOMETHING@\n",
            "header twice": PYTHON_TCL + "@HEADER@\n",
            "no depends": PYTHON_TCL.replace("@DEPENDS@\n", ""),
            "generated without generate": PYTHON_TCL + "@GENERATED@\n",
            "no conflict": PYTHON_TCL.replace("conflict PYTHON\n", ""),
            "conflict with other name": PYTHON_TCL.replace("conflict PYTHON", "conflict ROOT"),
            "no home var": PYTHON_TCL.replace("setenv       PYTHON_HOME @PREFIX@\n", ""),
            "two home vars": PYTHON_TCL + "setenv OTHER_HOME @PREFIX@\n",
        }
        for label, text in cases.items():
            with self.subTest(label):
                self.put_template("PYTHON", text)
                with self.assertRaises(FormatError):
                    modulefile.load_source(self.src, "PYTHON")
        self.put_template("PYTHON", PYTHON_TCL)
        with self.assertRaises(FormatError):
            modulefile.load_source(self.src, "NOPE")

    def test_generate_requires_placeholder(self):
        self.put_template("ROOT", ROOT_TCL.replace("@GENERATED@\n", ""), generate="#!/bin/sh\n")
        with self.assertRaises(FormatError):
            modulefile.load_source(self.src, "ROOT")


class TestMake(Sources):
    def make_root(self, runner=modulefile.run_generate):
        return modulefile.make_fixed(self.src, self.recipes, PRODUCTS, "ROOT", "V6.32.20_3.11.14",
                                     tool="v0.1", host="cupdev0", time="2026-12-01T10:00:00+09:00",
                                     runner=runner)

    def test_fixed(self):
        text = self.make_root()
        prefix = f"{PRODUCTS}/ROOT/V6.32.20_3.11.14"
        self.assertTrue(text.startswith("#%Module\n# generated by prod v0.1 on cupdev0 at 2026-12-01T10:00:00+09:00\n"))
        self.assertIn("modulefiles/ROOT/template.tcl, modulefiles/ROOT/generate, recipes/ROOT/V6.32.20_3.11.14.yml", text)
        self.assertIn(f"setenv       ROOTSYS            {prefix}\n", text)
        self.assertIn(f"setenv ROOT_PREFIX_SEEN {prefix}\n", text)  # generate got the version directory
        self.assertIn("module load PYTHON/V3.11.14", text)
        self.assertIn(f'$::env(PYTHON_HOME) ne "{PRODUCTS}/PYTHON/V3.11.14"', text)
        self.assertIn("if {[module-info mode load]} {", text)
        self.assertNotRegex(text, r"@[A-Z_]+@")
        if TCLSH:
            self.assertTrue(tcl_complete(text))

    def test_no_dependencies(self):
        text = modulefile.make_fixed(self.src, self.recipes, PRODUCTS, "PYTHON", "V3.11.14",
                                     tool="v0.1", host="h", time="t")
        self.assertIn("# no dependencies\n", text)
        self.assertNotIn("module load", text)

    def test_generate_failure(self):
        self.put_template("ROOT", ROOT_TCL, generate="#!/bin/sh\necho oops >&2\nexit 3\n")
        with self.assertRaisesRegex(FormatError, "exited with 3: oops"):
            self.make_root()

    def test_generate_output_with_placeholder(self):
        with self.assertRaises(FormatError):
            self.make_root(runner=lambda gen, prefix: "setenv X @PREFIX@")

    def test_missing_recipe(self):
        with self.assertRaises(FormatError):
            modulefile.make_fixed(self.src, self.recipes, PRODUCTS, "ROOT", "V9.99",
                                  tool="v", host="h", time="t")

    def test_unsafe_prefix(self):
        with self.assertRaises(FormatError):
            modulefile.make_fixed(self.src, self.recipes, "/home/cup soft/Products", "PYTHON", "V3.11.14",
                                  tool="v", host="h", time="t")

    def test_bundle(self):
        text = modulefile.make_bundle("3.1", 'PYTHON 3.11 + ROOT "6.32" {lsim} $x [y]',
                                      ["PYTHON/V3.11.14", "ROOT/V6.32.20_3.11.14-m2"],
                                      tool="v0.1", host="cupdev0", time="2026-12-01T10:00:00+09:00")
        lines = text.splitlines()
        self.assertEqual(lines[0], "#%Module")
        self.assertIn("conflict vlist", lines)
        self.assertEqual([l for l in lines if l.startswith("module load")],
                         ["module load PYTHON/V3.11.14", "module load ROOT/V6.32.20_3.11.14-m2"])
        self.assertIn('setenv PROD_VLIST "3.1"', lines)
        self.assertIn(r'module-whatis "vlist 3.1: PYTHON 3.11 + ROOT \"6.32\" \{lsim\} \$x \[y\]"', lines)
        if TCLSH:
            self.assertTrue(tcl_complete(text))


class TestTclQuote(unittest.TestCase):
    @unittest.skipUnless(TCLSH, "tclsh not installed")
    def test_tcl_complete_detects_broken_scripts(self):
        self.assertTrue(tcl_complete('setenv A "b"\n'))
        self.assertFalse(tcl_complete("if {1} {\n"))
        self.assertFalse(tcl_complete('puts "open\n'))

    def test_quote(self):
        self.assertEqual(modulefile.tcl_quote("plain"), '"plain"')
        self.assertEqual(modulefile.tcl_quote('a"b\\c$d[e]{f}'), r'"a\"b\\c\$d\[e\]\{f\}"')


class TestRecipe(unittest.TestCase):
    def test_loads(self):
        r = recipe.loads(ROOT_RECIPE, "ROOT", "V6.32.20_3.11.14")
        self.assertEqual(r.depends, [("PYTHON", "V3.11.14")])

    def test_errors(self):
        good = ROOT_RECIPE
        cases = {
            "wrong product": (good, "PYTHON", "V6.32.20_3.11.14"),
            "wrong version": (good, "ROOT", "V1"),
            "unknown key": (good + b'colour: "x"\n', "ROOT", "V6.32.20_3.11.14"),
            "bad dep": (good.replace(b'name: "PYTHON"', b'name: "python"'), "ROOT", "V6.32.20_3.11.14"),
            "dep extra key": (good.replace(b'version: "V3.11.14"}', b'version: "V3.11.14", x: "y"}'),
                              "ROOT", "V6.32.20_3.11.14"),
            "self dep": (good.replace(b'name: "PYTHON"', b'name: "ROOT"'), "ROOT", "V6.32.20_3.11.14"),
        }
        for label, (data, name, version) in cases.items():
            with self.subTest(label):
                with self.assertRaises(FormatError):
                    recipe.loads(data, name, version)

    def test_depends_from_suffix(self):
        self.assertEqual(recipe.depends_from_suffix("V6.32.20_3.11.14"), [("PYTHON", "V3.11.14")])
        self.assertEqual(recipe.depends_from_suffix("V6.32.08_2024.10-1"), [])  # Anaconda: no longer used
        self.assertEqual(recipe.depends_from_suffix("V11.1.3"), [])
        self.assertEqual(recipe.depends_from_suffix("V4.3"), [])


if __name__ == "__main__":
    unittest.main()
