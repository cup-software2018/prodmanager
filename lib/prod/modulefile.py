"""Fixed modulefiles and vlist bundle modulefiles.

A modulefile source in the git repository is `modulefiles/<NAME>/template.tcl` plus an optional
executable `modulefiles/<NAME>/generate`. `prodman release` fills the template once per version; the result
is frozen on the products server and is self-contained (it never sources other files).

Template rules (checked by load_source):
- starts with `#%Module`
- uses only the placeholders @NAME@ @VERSION@ @PREFIX@ @DEPENDS@ @GENERATED@ @HEADER@;
  @HEADER@ and @DEPENDS@ exactly once, @GENERATED@ exactly once if `generate` exists, else not at all
- has `conflict <NAME>`
- has exactly one `setenv <VAR> @PREFIX@` line; <VAR> is the product's "home variable", which other
  modulefiles use to check that the right version of this product is loaded
"""

import os
import re
import subprocess
from dataclasses import dataclass
from typing import Optional

from .errors import FormatError
from . import recipe as recipe_mod

_PLACEHOLDER_RE = re.compile(r"@([A-Z_]+)@")
_KNOWN = {"NAME", "VERSION", "PREFIX", "DEPENDS", "GENERATED", "HEADER"}
_HOME_RE = re.compile(r"^[ \t]*setenv[ \t]+([A-Za-z_][A-Za-z0-9_]*)[ \t]+@PREFIX@[ \t]*$", re.M)
_SAFE_PATH_RE = re.compile(r"^/[A-Za-z0-9._/-]+$")
_TCL_SPECIAL = {"\\": "\\\\", '"': '\\"', "$": "\\$", "[": "\\[", "]": "\\]", "{": "\\{", "}": "\\}"}


def tcl_quote(s):
    """Quote a string as a Tcl double-quoted word with every special character escaped."""
    return '"' + "".join(_TCL_SPECIAL.get(c, c) for c in s) + '"'


@dataclass
class Source:
    name: str
    template: str
    generate: Optional[str]  # path of the generate executable, or None
    home_var: str


def load_source(src_root, name):
    """Read and check the modulefile source of product name from the git modulefiles/ directory."""
    d = os.path.join(src_root, name)
    path = os.path.join(d, "template.tcl")
    try:
        with open(path, encoding="utf-8") as f:
            template = f.read()
    except FileNotFoundError:
        raise FormatError(f"no modulefile template {path}") from None
    gen = os.path.join(d, "generate")
    gen = gen if os.path.exists(gen) else None
    if gen and not os.access(gen, os.X_OK):
        raise FormatError(f"{gen} is not executable")

    what = f"modulefile template {name}"
    if not template.startswith("#%Module"):
        raise FormatError(f"{what}: must start with '#%Module'")
    used = _PLACEHOLDER_RE.findall(template)
    unknown = sorted(set(used) - _KNOWN)
    if unknown:
        raise FormatError(f"{what}: unknown placeholders: {', '.join('@%s@' % u for u in unknown)}")
    for ph in ("HEADER", "DEPENDS"):
        if used.count(ph) != 1:
            raise FormatError(f"{what}: @{ph}@ must appear exactly once")
    if used.count("GENERATED") != (1 if gen else 0):
        raise FormatError(f"{what}: @GENERATED@ must appear exactly once if 'generate' exists, else not at all")
    if not re.search(rf"^[ \t]*conflict[ \t]+{re.escape(name)}[ \t]*$", template, re.M):
        raise FormatError(f"{what}: missing 'conflict {name}'")
    homes = _HOME_RE.findall(template)
    if len(homes) != 1:
        raise FormatError(f"{what}: needs exactly one 'setenv <VAR> @PREFIX@' line (found {len(homes)})")
    return Source(name=name, template=template, generate=gen, home_var=homes[0])


def _safe_path(path):
    if not _SAFE_PATH_RE.match(path):
        raise FormatError(f"path '{path}' must be absolute and use only [A-Za-z0-9._/-]")
    return path


def depends_code(name, version, deps, products_dir, home_vars):
    """Tcl code that loads or checks dependencies by install path.

    deps: [(dep_name, dep_version)], home_vars: {dep_name: home variable of that product}.
    Runs only in load mode, so unloading never fails because a dependency is already gone.
    """
    if not deps:
        return "# no dependencies"
    lines = ["# dependencies, checked by install path", "if {[module-info mode load]} {"]
    for dname, dver in deps:
        prefix = _safe_path(os.path.join(products_dir, dname, dver))
        var = home_vars[dname]
        msg = f"{name}/{version} needs {dname} {dver}, but another {dname} is loaded"
        lines += [
            f"    if {{![is-loaded {dname}]}} {{",
            f"        module load {dname}/{dver}",
            f"    }} elseif {{![info exists ::env({var})] || $::env({var}) ne {tcl_quote(prefix)}}} {{",
            f"        error {tcl_quote(msg)}",
            "    }",
        ]
    lines.append("}")
    return "\n".join(lines)


def header(tool, host, time, sources, recipe=None):
    lines = [f"# generated by prodman {tool} on {host} at {time}", f"# source: {', '.join(sources)} @ {tool}"]
    if recipe:
        lines.append(f"# recipe: {recipe}")
    lines.append("# DO NOT EDIT. A released modulefile never changes.")
    return "\n".join(lines)


def run_generate(generate, prefix, timeout=300):
    """Run a product's generate script once with the version directory; returns its Tcl output."""
    try:
        out = subprocess.run([generate, prefix], capture_output=True, text=True, timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise FormatError(f"{generate} failed: {e}") from None
    if out.returncode != 0:
        raise FormatError(f"{generate} exited with {out.returncode}: {out.stderr.strip()}")
    return out.stdout.rstrip("\n")


def render(src, version, prefix, depends, generated, head):
    values = {
        "NAME": src.name, "VERSION": version, "PREFIX": _safe_path(prefix),
        "DEPENDS": depends, "GENERATED": generated, "HEADER": head,
    }
    for key in ("DEPENDS", "GENERATED", "HEADER"):
        if _PLACEHOLDER_RE.search(values[key]):
            raise FormatError(f"{src.name}: @{key}@ content must not contain placeholders")
    text = _PLACEHOLDER_RE.sub(lambda m: values[m.group(1)], src.template)
    return text if text.endswith("\n") else text + "\n"


def make_fixed(src_root, recipes_root, products_dir, name, version, *, tool, host, time,
               runner=run_generate):
    """Build the fixed modulefile text of one product version. The recipe is the one saved next to the version
    if there is one, else the tool's (recipe.find)."""
    src = load_source(src_root, name)
    rec = recipe_mod.find(products_dir, recipes_root, name, version)
    home_vars = {d: load_source(src_root, d).home_var for d, _ in rec.depends}
    prefix = os.path.join(products_dir, name, version)
    dep = depends_code(name, version, rec.depends, products_dir, home_vars)
    generated = runner(src.generate, prefix) if src.generate else ""
    sources = [f"modulefiles/{name}/template.tcl"]
    if src.generate:
        sources.append(f"modulefiles/{name}/generate")
    return render(src, version, prefix, dep, generated, header(tool, host, time, sources, rec.origin(tool)))


def make_bundle(vlist_name, description, modules, *, tool, host, time):
    """Build the vlist bundle modulefile `modulefiles/vlist/<name>`."""
    lines = [
        "#%Module",
        f"# generated by prodman {tool} on {host} at {time} for vlist {vlist_name}",
        "# DO NOT EDIT.",
        f"module-whatis {tcl_quote(f'vlist {vlist_name}: {description}')}",
        "conflict vlist",
    ]
    lines += [f"module load {m}" for m in modules]
    lines.append(f"setenv PROD_VLIST {tcl_quote(vlist_name)}")
    return "\n".join(lines) + "\n"
